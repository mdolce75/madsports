-- Datos de SIDGAD en tablas propias (épica #215), además del HTML guardado en source_snapshot y sidgad_game_sheet, que
-- sigue siendo la fuente: las tablas se llenan parseándolo (SidgadNormalizer), sin pedidos a SIDGAD.

-- Competiciones del catálogo (cap_ls_1.php): id = idc de SIDGAD.
create table sidgad_competition (
    id             integer primary key,
    federation_id  integer not null,
    federation     varchar(10),
    season_id      integer not null,
    season_year    integer,
    name           varchar(300) not null,
    tournament     varchar(10),
    level          varchar(40),
    branch         varchar(20),
    division       integer not null,
    period_minutes integer not null,
    updated_at     timestamp with time zone not null
);
create index sidgad_competition_year on sidgad_competition (federation, season_year);

-- Equipos de cada competición (teams_array_<idc> del catálogo).
create table sidgad_team (
    id             bigint generated by default as identity primary key,
    competition_id integer not null references sidgad_competition (id),
    team_id        integer not null,
    club_id        integer not null,
    code           varchar(40),
    name           varchar(200) not null,
    logo           varchar(100),
    constraint sidgad_team_unico unique (competition_id, team_id)
);
create index sidgad_team_club on sidgad_team (club_id);

-- Partidos del calendario (cap_cal_idc_<idc>_1.php): idp es el del acta (null si todavía no tiene).
create table sidgad_match (
    id             bigint generated by default as identity primary key,
    competition_id integer not null references sidgad_competition (id),
    idp            integer,
    round          integer not null,
    match_date     date,
    match_time     time,
    venue          varchar(200),
    home_team_id   integer not null,
    home_club_id   integer not null,
    home_name      varchar(200),
    away_team_id   integer not null,
    away_club_id   integer not null,
    away_name      varchar(200),
    home_goals     integer,
    away_goals     integer,
    played         boolean not null
);
create index sidgad_match_competition on sidgad_match (competition_id);
create index sidgad_match_idp on sidgad_match (idp);
create index sidgad_match_date on sidgad_match (match_date);
create index sidgad_match_home_club on sidgad_match (home_club_id);
create index sidgad_match_away_club on sidgad_match (away_club_id);
