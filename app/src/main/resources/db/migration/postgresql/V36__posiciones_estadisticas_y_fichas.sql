-- Tablas de posiciones, estadísticas por jugador y fichas de temporada de SIDGAD en tablas propias (épica #215),
-- parseadas de las copias de source_snapshot (SidgadNormalizer).

-- La tabla de posiciones de cada competición (cap_clasif_idc_<idc>_1.php), por grupo ("IMPAR", "PAR"...).
create table sidgad_standing (
    id             bigint generated by default as identity primary key,
    competition_id integer not null references sidgad_competition (id),
    group_name     varchar(100),
    position       integer not null,
    club_id        integer not null,
    name           varchar(200),
    code           varchar(40),
    points         integer not null,
    played         integer not null,
    won            integer not null,
    drawn          integer not null,
    lost           integer not null,
    goals_for      integer not null,
    goals_against  integer not null,
    goal_diff      integer not null
);
create index sidgad_standing_competition on sidgad_standing (competition_id);
create index sidgad_standing_club on sidgad_standing (club_id);

-- Las estadísticas por jugador de cada competición (cap_stats_1_<idc>.php).
create table sidgad_player_stats (
    id                 bigint generated by default as identity primary key,
    competition_id     integer not null references sidgad_competition (id),
    player_id          integer not null,
    team_id            integer not null,
    team_code          varchar(40),
    club_id            integer not null,
    name               varchar(200),
    goals              integer not null,
    games              integer not null,
    assists            integer not null,
    penalties_scored   integer not null,
    penalties_taken    integer not null,
    direct_free_scored integer not null,
    direct_free_taken  integer not null,
    blue_cards         integer not null,
    red_cards          integer not null
);
create index sidgad_player_stats_competition on sidgad_player_stats (competition_id);
create index sidgad_player_stats_player on sidgad_player_stats (player_id);

-- La ficha de temporada de cada jugador (profiles/cap_profileseason_<id>_1_<temporada>.php): sus partidos, incluidos los
-- que no tienen acta publicada (idp null).
create table sidgad_player_season_match (
    id                 bigint generated by default as identity primary key,
    player_id          integer not null,
    season_id          integer not null,
    competition_name   varchar(300),
    match_date         date,
    home_name          varchar(200),
    away_name          varchar(200),
    home_goals         integer not null,
    away_goals         integer not null,
    idp                integer,
    goals              integer not null,
    assists            integer not null,
    direct_free_scored integer not null,
    direct_free_taken  integer not null,
    penalties_scored   integer not null,
    penalties_taken    integer not null,
    blue_cards         integer not null,
    red_cards          integer not null
);
create index sidgad_player_season_match_player on sidgad_player_season_match (player_id, season_id);
create index sidgad_player_season_match_idp on sidgad_player_season_match (idp);
