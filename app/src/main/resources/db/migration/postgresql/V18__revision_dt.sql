-- Revisión de Métricas DT.

-- Cupo del mes: cada partido que el DT empieza queda registrado aunque después lo elimine (eliminar un partido no
-- devuelve el lugar en el cupo).
create table partido_creado_dt (
    id         bigint generated by default as identity primary key,
    usuario_id bigint    not null references usuario (id) on delete cascade,
    creado     timestamptz not null
);
create index partido_creado_dt_usuario on partido_creado_dt (usuario_id, creado);
insert into partido_creado_dt (usuario_id, creado) select usuario_id, creado from partido_dt;

-- El partido se borra con su equipo (y con el usuario, que borra sus equipos): la referencia pasa a ON DELETE CASCADE,
-- como las demás tablas del DT. En PostgreSQL la restricción tiene el nombre que le da el motor por defecto.
alter table partido_dt drop constraint partido_dt_equipo_id_fkey;
alter table partido_dt add constraint partido_dt_equipo foreign key (equipo_id) references equipo_dt (id) on delete cascade;

-- Columnas que quedaron sin uso con los equipos del ABM (V16). Al borrarlas, PostgreSQL borra las restricciones únicas
-- que las incluían. El id de cada jugador vuelve a ser único por DT.
alter table jugador_dt drop column categoria;
alter table jugador_dt drop column rama;
alter table jugador_dt add constraint jugador_dt_id_unico unique (usuario_id, jugador_id);

alter table partido_dt drop column categoria;
alter table partido_dt drop column rama;

alter table equipo_dt drop column categoria;
alter table equipo_dt drop column rama;
