-- Usuarios de la web y sus perfiles (lo que el usuario compró: un usuario puede tener varios).
create table usuario (
    id             bigint generated by default as identity primary key,
    usuario        varchar(30)  not null unique,
    clave          varchar(100) not null,
    email          varchar(120) not null unique,
    nombre         varchar(60)  not null,
    apellido       varchar(60)  not null,
    club_id        int          not null,
    club_nombre    varchar(80)  not null,
    club_codigo    varchar(20)  not null,
    -- Solo perfiles de jugador: DNI y jugador de SIDGAD (id_player) elegido en el registro.
    dni            varchar(10) unique,
    jugador_id     int unique,
    jugador_nombre varchar(120),
    creado         timestamp    not null
);

create table usuario_perfil (
    usuario_id bigint      not null references usuario (id) on delete cascade,
    perfil     varchar(20) not null,
    primary key (usuario_id, perfil)
);
