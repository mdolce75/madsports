-- Actas de SIDGAD en tablas propias (épica #215): las planillas y los eventos de cada partido, parseados del HTML de
-- sidgad_game_sheet (SidgadNormalizer). idp une con sidgad_match, sin clave foránea: los partidos de una competición se
-- reemplazan al normalizar su calendario.

-- Jugadores (id_player de SIDGAD), con el último nombre visto en un acta.
create table sidgad_player (
    id         integer primary key,
    name       varchar(200) not null,
    surname    varchar(200),
    updated_at timestamp with time zone not null
);

-- La planilla de cada equipo en el partido: una fila por jugador citado.
create table sidgad_match_lineup (
    id                 bigint generated by default as identity primary key,
    idp                integer not null,
    player_id          integer,
    home               boolean not null,
    team_name          varchar(200),
    shirt_number       varchar(10),
    name               varchar(200),
    starter            boolean not null,
    goalkeeper         boolean not null,
    goals              integer not null,
    yellow_cards       integer not null,
    blue_cards         integer not null,
    red_cards          integer not null,
    penalties_scored   integer not null,
    penalties_taken    integer not null,
    direct_free_scored integer not null,
    direct_free_taken  integer not null
);
create index sidgad_match_lineup_idp on sidgad_match_lineup (idp);
create index sidgad_match_lineup_player on sidgad_match_lineup (player_id);

-- Los eventos del acta: goles, tarjetas (amarilla, azul y roja) y faltas de equipo, con período y minuto.
create table sidgad_match_event (
    id           bigint generated by default as identity primary key,
    idp          integer not null,
    period       integer not null,
    event_minute integer not null,
    event_second integer not null,
    event_type   varchar(20) not null,
    team_id      integer not null,
    club_id      integer not null,
    team_code    varchar(40),
    player_name  varchar(200),
    player_id    integer
);
create index sidgad_match_event_idp on sidgad_match_event (idp);
create index sidgad_match_event_player on sidgad_match_event (player_id);
