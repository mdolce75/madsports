-- Tipos de suscripción (lo que el usuario compra) y, en cada usuario, su suscripción y cuántos informes pidió.
create table suscripcion_type (
    id     bigint generated by default as identity primary key,
    codigo varchar(20) not null unique,
    nombre varchar(40) not null,
    meses  int         not null
);

insert into suscripcion_type (codigo, nombre, meses) values ('MENSUAL', 'Mensual', 1);
insert into suscripcion_type (codigo, nombre, meses) values ('TRIMESTRAL', 'Trimestral', 3);
insert into suscripcion_type (codigo, nombre, meses) values ('SEMESTRAL', 'Semestral', 6);
insert into suscripcion_type (codigo, nombre, meses) values ('ANUAL', 'Anual', 12);

alter table usuario add column suscripcion_type_id bigint references suscripcion_type (id);
alter table usuario add column suscripcion_desde date;
alter table usuario add column suscripcion_hasta date;
alter table usuario add column informes_pedidos int default 0 not null;
