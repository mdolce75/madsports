-- Verificación de email y recuperación de clave.
alter table usuario add column email_verificado boolean default false not null;
-- Los usuarios anteriores a la verificación quedan habilitados.
update usuario set email_verificado = true;

-- Enlaces de un solo uso enviados por mail. Se guarda el hash (SHA-256) del token, nunca el token.
create table token_usuario (
    id         bigint generated by default as identity primary key,
    usuario_id bigint      not null references usuario (id) on delete cascade,
    tipo       varchar(20) not null,
    hash       varchar(64) not null unique,
    creado     timestamp   not null,
    expira     timestamp   not null,
    usado      boolean     default false not null
);
