-- Planilla DT en vivo: los partidos que carga cada DT y sus acciones (cada una de un jugador, con tiempo y segundo).
create table partido_dt (
    id             bigint generated by default as identity primary key,
    usuario_id     bigint      not null references usuario (id) on delete cascade,
    federacion     varchar(3)  not null,
    club_id        int         not null,
    categoria      varchar(30) not null,
    rama           varchar(12) not null,
    idc            int,
    idp            int,
    torneo         varchar(40),
    rival          varchar(60) not null,
    fecha          date        not null,
    es_local       boolean     not null,
    minutos_tiempo int         not null,
    estado         varchar(12) not null,
    tiempo_actual  int         default 1 not null,
    -- Reloj: hora en que arrancó o se reanudó (null si está parado) y segundos jugados del tiempo hasta ese momento.
    reloj_desde    timestamp,
    reloj_segundos int         default 0 not null,
    goles_favor    int         default 0 not null,
    goles_contra   int         default 0 not null,
    creado         timestamp   not null,
    cerrado        timestamp,
    -- Un partido de SIDGAD se carga una sola vez por equipo (los amistosos no tienen idp).
    unique (club_id, categoria, rama, idp)
);
create index partido_dt_usuario on partido_dt (usuario_id, fecha);

create table accion_dt (
    -- uuid generado en el teléfono: se puede cargar sin señal y reenviar sin duplicar.
    id             varchar(36) primary key,
    partido_id     bigint      not null references partido_dt (id) on delete cascade,
    jugador_id     int         not null,
    jugador_nombre varchar(80) not null,
    tipo           varchar(16) not null,
    resultado      varchar(12),
    tiempo         int         not null,
    segundo        int         not null,
    creada         timestamp   not null,
    -- Deshacer: la acción queda marcada como borrada (no se borra la fila).
    borrada        timestamp
);
create index accion_dt_partido on accion_dt (partido_id);
