                              vigente_hasta)
    values ('CLUB_FREE', 'Club free', 'CLUB', 0, 0, 0, 0, date '2026-12-31');

-- Jugador free: hasta 5 informes por mes calendario.
update suscripcion_type set informes_por_mes = 5 where codigo = 'PLAYER_FREE';

-- Cada informe pedido, con su fecha: el cupo del mes se cuenta desde acá (informes_pedidos queda como total histórico).
create table informe_pedido (
    id         bigint generated by default as identity primary key,
    usuario_id bigint not null references usuario (id) on delete cascade,
    creado     timestamptz not null
);
create index informe_pedido_usuario on informe_pedido (usuario_id, creado);
