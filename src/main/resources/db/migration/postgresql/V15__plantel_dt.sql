-- Plantel de cada equipo del DT: la primera vez se arma con el de las actas de SIDGAD y después el DT lo edita (alta,
-- baja y cambios). Una baja no borra al jugador: sus acciones siguen en los partidos e informes.
create table jugador_dt (
    id         bigint generated by default as identity primary key,
    usuario_id bigint      not null references usuario (id) on delete cascade,
    categoria  varchar(30) not null,
    rama       varchar(12) not null,
    -- El id del jugador en las acciones: su id_player de SIDGAD, o uno propio (desde 900000000) si lo agrega el DT.
    jugador_id int         not null,
    nombre     varchar(40) not null,
    apellido   varchar(40) not null,
    numero     varchar(3),
    arquero    boolean     not null,
    activo     boolean     default true not null,
    creado     timestamptz   not null,
    unique (usuario_id, categoria, rama, jugador_id)
);

-- El campeonato del partido admite hasta 60 caracteres, como valida la pantalla.
alter table partido_dt alter column torneo set data type varchar(60);
