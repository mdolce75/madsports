-- Equipos del DT: los arma él en el ABM (solo un nombre), sin límite. Cada partido es de un equipo y el plantel ya no
-- sale de SIDGAD: los jugadores los carga el DT y cada uno puede estar en varios equipos.
create table equipo_dt (
    id         bigint generated by default as identity primary key,
    usuario_id bigint      not null references usuario (id) on delete cascade,
    nombre     varchar(60) not null,
    creado     timestamptz   not null,
    -- Solo en los equipos de antes (los que se elegían en el registro), para pasarles sus partidos y jugadores.
    categoria  varchar(30),
    rama       varchar(12)
);

-- Los equipos de antes pasan con su nombre ("PRIMERA" y "MASCULINO" -> "Primera Masculino"; "JUVENIL:A" -> "Juvenil A").
insert into equipo_dt (usuario_id, nombre, creado, categoria, rama)
select usuario_id,
       upper(left(nivel, 1)) || lower(substring(nivel, 2)) || case when letra is null then '' else ' ' || letra end
           || ' ' || upper(left(rama, 1)) || lower(substring(rama, 2)),
       current_timestamp, categoria, rama
from (select usuario_id, categoria, rama,
             case when position(':' in categoria) > 0 then left(categoria, position(':' in categoria) - 1) else categoria end nivel,
             case when position(':' in categoria) > 0 then substring(categoria, position(':' in categoria) + 1) end letra
      from (select usuario_id, categoria, rama from usuario_equipo_dt
            union select usuario_id, categoria, rama from partido_dt
            union select usuario_id, categoria, rama from jugador_dt where jugador_id >= 900000000) t) x;

alter table partido_dt add column equipo_id bigint references equipo_dt (id);
update partido_dt p set equipo_id = (select e.id from equipo_dt e
                                     where e.usuario_id = p.usuario_id and e.categoria = p.categoria and e.rama = p.rama);
alter table partido_dt alter column equipo_id set not null;
alter table partido_dt alter column categoria drop not null;
alter table partido_dt alter column rama drop not null;

-- Plantel: los jugadores traídos de las actas de SIDGAD salen (sus acciones conservan el nombre); los que cargó el DT
-- quedan en el equipo donde estaban.
delete from jugador_dt where jugador_id < 900000000;
create table jugador_equipo_dt (
    jugador_dt_id bigint not null references jugador_dt (id) on delete cascade,
    equipo_id     bigint not null references equipo_dt (id) on delete cascade,
    primary key (jugador_dt_id, equipo_id)
);
insert into jugador_equipo_dt (jugador_dt_id, equipo_id)
select j.id, e.id from jugador_dt j
join equipo_dt e on e.usuario_id = j.usuario_id and e.categoria = j.categoria and e.rama = j.rama;
alter table jugador_dt alter column categoria drop not null;
alter table jugador_dt alter column rama drop not null;

-- El registro ya no pide los equipos.
drop table usuario_equipo_dt;
